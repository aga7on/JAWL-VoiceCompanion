"""Report owned deviations of the pinned JAWL snapshot from upstream th0r3nt/JAWL.

Compares ``runtime/jawl-sources/jawl-20260906-daily-v2`` against an upstream
checkout and writes:

* a markdown baseline report (added / modified / unchanged / unstaged drift);
* one combined unified patch with every owned deviation.

Usage::

    python scripts/kernel_upstream_diff.py \\
        --upstream .kernel-upstream \\
        --report docs/research/kernel-upstream-baseline-20261029.md \\
        --patch patches/kernel/owned-deviations.patch

Regenerate after every snapshot change and confirm the report shows
``unstaged 0`` against a clean git tree (drift means the manifest or the
commit is stale).
"""

from __future__ import annotations

import argparse
import difflib
import subprocess
import sys
from pathlib import Path


REPO_ROOT = Path(__file__).resolve().parents[1]
DEFAULT_SOURCE = REPO_ROOT / "runtime" / "jawl-sources" / "jawl-20260906-daily-v2"
MANIFEST_NAME = "SOURCE_MANIFEST.json"


def _is_generated(relative: Path) -> bool:
    """Generated runtime state never belongs to the deviation inventory."""

    if relative.name == MANIFEST_NAME:
        return True
    if relative.suffix.lower() == ".pyc" and "__pycache__" in relative.parts:
        return True
    return bool(relative.parts) and relative.parts[0] in {"logs", "sandbox"}


def _collect(root: Path) -> dict[str, Path]:
    files: dict[str, Path] = {}
    for path in sorted(root.rglob("*")):
        if not path.is_file() or path.is_symlink():
            continue
        relative = path.relative_to(root)
        if _is_generated(relative):
            continue
        files[relative.as_posix()] = path
    return files


def _git(args: list[str], cwd: Path) -> str:
    result = subprocess.run(
        ["git", *args],
        cwd=cwd,
        capture_output=True,
        text=True,
    )
    if result.returncode != 0:
        raise RuntimeError(f"git {' '.join(args)} failed: {result.stderr.strip()}")
    return result.stdout


def _upstream_identity(upstream: Path) -> tuple[str, str]:
    sha = _git(["rev-parse", "HEAD"], upstream).strip()
    subject = _git(["log", "-1", "--format=%s"], upstream).strip()
    return sha, subject


def _unstaged_paths(repo: Path, source: Path) -> set[str]:
    """Snapshot files that differ from (or are absent in) the git index."""

    prefix = source.relative_to(repo).as_posix()
    changed = _git(
        ["diff", "--name-only", "HEAD", "--", prefix],
        repo,
    ).splitlines()
    untracked = _git(
        ["ls-files", "--others", "--exclude-standard", "--", prefix],
        repo,
    ).splitlines()
    drifted: set[str] = set()
    for name in changed + untracked:
        path = Path(name)
        relative = path.relative_to(prefix) if str(path).startswith(prefix) else path
        if not _is_generated(Path(relative)):
            drifted.add(Path(relative).as_posix())
    return drifted


def _unified(old: str, new: str, rel: str) -> list[str]:
    return list(
        difflib.unified_diff(
            old.splitlines(keepends=True),
            new.splitlines(keepends=True),
            fromfile=f"a/{rel}",
            tofile=f"b/{rel}",
        )
    )


def generate(
    source: Path,
    upstream: Path,
    report_path: Path,
    patch_path: Path,
    repo: Path,
) -> dict[str, object]:
    snapshot = _collect(source)
    baseline = _collect(upstream)
    sha, subject = _upstream_identity(upstream)

    added = sorted(set(snapshot) - set(baseline))
    modified = sorted(
        rel
        for rel in set(snapshot) & set(baseline)
        if snapshot[rel].read_bytes() != baseline[rel].read_bytes()
    )
    unchanged = sorted(
        rel
        for rel in set(snapshot) & set(baseline)
        if snapshot[rel].read_bytes() == baseline[rel].read_bytes()
    )
    drifted = sorted(_unstaged_paths(repo, source) & set(snapshot))

    patch_lines: list[str] = []
    for rel in added:
        patch_lines.extend(_unified("", snapshot[rel].read_text(encoding="utf-8", errors="replace"), rel))
    for rel in modified:
        patch_lines.extend(
            _unified(
                baseline[rel].read_text(encoding="utf-8", errors="replace"),
                snapshot[rel].read_text(encoding="utf-8", errors="replace"),
                rel,
            )
        )
    patch_path.parent.mkdir(parents=True, exist_ok=True)
    patch_path.write_text("".join(patch_lines), encoding="utf-8")

    lines: list[str] = []
    lines.append("# Kernel upstream baseline — 2026-10-29")
    lines.append("")
    lines.append(
        "Generated by `scripts/kernel_upstream_diff.py`; regenerate after every"
        " snapshot change. `unstaged` must stay `0` against a clean git tree."
    )
    lines.append("")
    lines.append(f"- Snapshot: `{source.relative_to(repo).as_posix()}`")
    lines.append(f"- Upstream: `th0r3nt/JAWL` @ `{sha[:12]}` — {subject}")
    lines.append(f"- Patch: `{patch_path.relative_to(repo).as_posix()}` ({len(patch_lines)} diff lines)")
    lines.append("")
    lines.append("## Summary")
    lines.append("")
    lines.append("| Category | Count |")
    lines.append("| --- | --- |")
    lines.append(f"| Added (owned files) | {len(added)} |")
    lines.append(f"| Modified (owned changes) | {len(modified)} |")
    lines.append(f"| Unchanged | {len(unchanged)} |")
    lines.append(f"| Unstaged drift | {len(drifted)} |")
    lines.append("")
    lines.append("## Added (owned files)")
    lines.append("")
    for rel in added:
        lines.append(f"- `{rel}`")
    lines.append("")
    lines.append("## Modified (owned changes)")
    lines.append("")
    for rel in modified:
        lines.append(f"- `{rel}`")
    lines.append("")
    if drifted:
        lines.append("## Unstaged drift (commit or regenerate)")
        lines.append("")
        for rel in drifted:
            lines.append(f"- `{rel}`")
        lines.append("")

    report_path.parent.mkdir(parents=True, exist_ok=True)
    report_path.write_text("\n".join(lines), encoding="utf-8")

    return {
        "added": len(added),
        "modified": len(modified),
        "unchanged": len(unchanged),
        "unstaged": len(drifted),
        "patch_lines": len(patch_lines),
    }


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--upstream", type=Path, required=True)
    parser.add_argument("--report", type=Path, required=True)
    parser.add_argument("--patch", type=Path, required=True)
    parser.add_argument("--source", type=Path, default=DEFAULT_SOURCE)
    parser.add_argument("--repo", type=Path, default=REPO_ROOT)
    args = parser.parse_args()
    stats = generate(
        source=args.source.resolve(),
        upstream=args.upstream.resolve(),
        report_path=(args.repo / args.report).resolve()
        if not args.report.is_absolute()
        else args.report,
        patch_path=(args.repo / args.patch).resolve()
        if not args.patch.is_absolute()
        else args.patch,
        repo=args.repo.resolve(),
    )
    print(
        f"report: {args.report} "
        f"({stats['added']} added, {stats['modified']} modified, "
        f"{stats['unstaged']} unstaged, {stats['unchanged']} unchanged)"
    )
    print(f"patch:  {args.patch} ({stats['patch_lines']} diff lines)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
